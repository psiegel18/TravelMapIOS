import Foundation

struct ListFileGenerator {

    /// Generate a .list file from matched segments.
    /// Merges consecutive segments on the same route into single lines.
    static func generate(from segments: [MatchedSegment], tripName: String? = nil) -> String {
        var lines: [String] = []

        // Header
        let dateStr = Date().formatted(date: .abbreviated, time: .omitted)
        lines.append("# Road trip recorded \(dateStr)")
        if let name = tripName {
            lines.append("# \(name)")
        }
        lines.append("# Generated by TravelMapping iOS App")
        lines.append("")

        // Sort by entry time
        let sorted = segments.sorted { $0.entryTime < $1.entryTime }

        // Merge consecutive segments on the same route
        let merged = mergeConsecutive(sorted)

        // Group by region for organized output
        let grouped = Dictionary(grouping: merged) { $0.region }

        for region in grouped.keys.sorted() {
            guard let regionSegments = grouped[region] else { continue }
            for seg in regionSegments {
                let wp1 = seg.direction == .reverse ? seg.endWaypoint : seg.startWaypoint
                let wp2 = seg.direction == .reverse ? seg.startWaypoint : seg.endWaypoint
                lines.append("\(seg.region) \(seg.routeName) \(wp1) \(wp2)")
            }
        }

        lines.append("")
        return lines.joined(separator: "\n")
    }

    /// Merge consecutive segments that share the same route root
    /// into a single segment spanning from first waypoint to last.
    private static func mergeConsecutive(_ segments: [MatchedSegment]) -> [MatchedSegment] {
        guard !segments.isEmpty else { return [] }

        var result: [MatchedSegment] = []
        var current = segments[0]

        for i in 1..<segments.count {
            let next = segments[i]

            // Can merge if same route and endpoints connect
            if next.root == current.root && canMerge(current: current, next: next) {
                // Extend current to cover the next segment
                let mergedEnd: String
                if current.direction == .forward {
                    mergedEnd = next.direction == .forward ? next.endWaypoint : next.startWaypoint
                } else {
                    mergedEnd = next.direction == .reverse ? next.startWaypoint : next.endWaypoint
                }

                current = MatchedSegment(
                    id: current.id,
                    root: current.root,
                    listName: current.listName,
                    startWaypoint: current.startWaypoint,
                    endWaypoint: mergedEnd,
                    entryTime: current.entryTime,
                    exitTime: next.exitTime,
                    direction: current.direction,
                    confidence: min(current.confidence, next.confidence)
                )
            } else {
                result.append(current)
                current = next
            }
        }
        result.append(current)

        return result
    }

    private static func canMerge(current: MatchedSegment, next: MatchedSegment) -> Bool {
        if current.direction == .forward && next.direction == .forward {
            return current.endWaypoint == next.startWaypoint
        }
        if current.direction == .reverse && next.direction == .reverse {
            return current.startWaypoint == next.endWaypoint
        }
        return false
    }

    // MARK: - Generate from Map Segments (for segment selection export)

    /// Generate .list text from selected MapSegments + route metadata.
    static func generateFromMapSegments(
        _ segments: [TravelMappingAPI.MapSegment],
        routeMetadata: [TravelMappingAPI.RouteMetadata]
    ) -> String {
        var lines: [String] = []
        lines.append("# Selected segments")
        lines.append("# Generated by TravelMapping iOS App")
        lines.append("")

        // Build root → listName lookup
        let rootToName: [String: String] = Dictionary(
            routeMetadata.map { ($0.root, $0.listName) },
            uniquingKeysWith: { first, _ in first }
        )

        // Group segments by root, merge consecutive
        let sorted = segments.sorted { a, b in
            if a.root != b.root { return a.root < b.root }
            return a.orderIndex < b.orderIndex
        }

        struct SimpleSegment {
            let root: String
            let listName: String
            var startWaypoint: String
            var endWaypoint: String
        }

        var merged: [SimpleSegment] = []
        var current: SimpleSegment?

        for seg in sorted {
            let listName = rootToName[seg.root] ?? seg.root

            if var cur = current, cur.root == seg.root, cur.endWaypoint == seg.startName {
                // Merge: extend current
                cur.endWaypoint = seg.endName
                current = cur
            } else {
                if let cur = current {
                    merged.append(cur)
                }
                current = SimpleSegment(
                    root: seg.root,
                    listName: listName,
                    startWaypoint: seg.startName,
                    endWaypoint: seg.endName
                )
            }
        }
        if let cur = current {
            merged.append(cur)
        }

        // Group by region
        let grouped = Dictionary(grouping: merged) { seg -> String in
            String(seg.listName.split(separator: " ").first ?? "")
        }

        for region in grouped.keys.sorted() {
            guard let segs = grouped[region] else { continue }
            for seg in segs {
                let parts = seg.listName.split(separator: " ", maxSplits: 1)
                let regionCode = parts.count > 0 ? String(parts[0]) : ""
                let routeName = parts.count > 1 ? String(parts[1]) : ""
                lines.append("\(regionCode) \(routeName) \(seg.startWaypoint) \(seg.endWaypoint)")
            }
        }

        lines.append("")
        return lines.joined(separator: "\n")
    }
}

// MARK: - List Line

/// One single-region .list entry (`Region Route Waypoint1 Waypoint2`).
struct ListLine: Hashable, Identifiable, Sendable {
    let region: String
    let route: String
    let waypoint1: String
    let waypoint2: String
    /// The visible waypoint labels of this exact TM route, in order, when known. Lets the
    /// merger extend an existing line that touches or overlaps this one instead of adding
    /// a second line for the same road.
    var routeLabels: [String] = []

    var id: String { text }
    var text: String { "\(region) \(route) \(waypoint1) \(waypoint2)" }

    static func == (a: ListLine, b: ListLine) -> Bool { a.text == b.text }
    func hash(into hasher: inout Hasher) { hasher.combine(text) }
}

// MARK: - List File Merger

/// Inserts new lines into an existing .list file the way its owner would.
/// People organize their files very differently (sectioned by country → system → state,
/// sorted by region, sorted by route number, or chronological trip blocks), so placement
/// is learned from the file's own neighbors rather than a fixed schema. Existing lines are
/// never reordered. The one edit: when a new stretch overlaps or shares an endpoint with a
/// line already on the same route, that line's endpoints are widened instead of adding a
/// second line for the same road. Separate pieces (a gap between them) stay separate.
enum ListFileMerger {

    struct Placement: Identifiable, Sendable {
        let line: ListLine
        /// 1-based line number in the merged output
        let lineNumber: Int
        /// Nearest section header above the inserted line, if any
        let section: String?
        /// Set when `line` widened an existing entry instead of being inserted: that
        /// entry's data before and after (no comment)
        var extended: (from: String, to: String)? = nil
        /// Other lines of the same route folded into the widened line and removed
        /// from the file (reported once, on the first placement for that line)
        var absorbed: [String] = []
        var id: String { line.id }
        /// What this placement leaves in the file
        var resultText: String { extended?.to ?? line.text }
    }

    struct Result: Sendable {
        let text: String
        let placements: [Placement]
        /// New lines skipped because the file already contains them
        let duplicates: [ListLine]
    }

    private enum Kind {
        case data(regions: [String], routes: [String], waypoints: [String])
        case header
        case comment
        case blank
    }

    private struct Entry {
        var raw: String
        var kind: Kind
        var inserted: ListLine? = nil
        /// New lines that widened this entry, with the entry's data before each
        var extendedBy: [(line: ListLine, from: String)] = []
        /// Same-route lines merged into this one and removed
        var absorbed: [String] = []

        var isData: Bool { if case .data = kind { return true } else { return false } }
        var isBoundary: Bool {
            switch kind {
            case .header, .blank: return true
            default: return false
            }
        }
        var regions: [String] { if case .data(let r, _, _) = kind { return r } else { return [] } }
        var routes: [String] { if case .data(_, let r, _) = kind { return r } else { return [] } }
        var waypoints: [String] { if case .data(_, _, let w) = kind { return w } else { return [] } }
        var primaryRegion: String { regions.first ?? "" }
        var primaryRoute: String { routes.first ?? "" }
    }

    /// - Parameters:
    ///   - existing: current .list file contents (empty for a brand-new file)
    ///   - newLines: lines to add
    ///   - blockTitle: header text used when appending a trip block (chronological files,
    ///     or lines with nowhere better to go)
    ///   - appendOnly: skip placement and always append one block (user preference)
    static func merge(existing: String, newLines: [ListLine], blockTitle: String, appendOnly: Bool = false) -> Result {
        // Split on \n and keep any \r with its line, so files that mix CRLF and LF
        // round-trip byte for byte; inserted lines follow whichever ending dominates.
        var rawLines = existing.components(separatedBy: "\n")
        let hadTrailingNewline = rawLines.last == ""
        if hadTrailingNewline { rawLines.removeLast() }
        let crlfCount = rawLines.filter { $0.hasSuffix("\r") }.count
        let newLineSuffix = crlfCount * 2 > rawLines.count ? "\r" : ""

        var entries = rawLines.map { Entry(raw: $0, kind: classify(Self.stripCR($0))) }
        let placesByFit = !(appendOnly || isChronological(entries))

        // Dedup against the file and within the batch
        var seen = Set<String>()
        for entry in entries where entry.isData && Set(entry.regions).count == 1 && Set(entry.routes).count == 1 {
            seen.insert(dedupKey(region: entry.primaryRegion, route: entry.primaryRoute, entry.waypoints))
        }
        var toInsert: [ListLine] = []
        var duplicates: [ListLine] = []
        for line in newLines {
            let key = dedupKey(region: line.region, route: line.route, [line.waypoint1, line.waypoint2])
            if seen.contains(key) {
                duplicates.append(line)
            } else {
                seen.insert(key)
                toInsert.append(line)
            }
        }

        // Widen existing lines on the same route rather than adding a second line. Not for
        // trip-block files or the append-only preference: there each trip gets its own block.
        if placesByFit {
            var removed = Set<Int>()
            toInsert = toInsert.filter { line in
                switch extend(line, in: &entries, removed: &removed) {
                case .notApplicable: return true
                case .covered: duplicates.append(line); return false
                case .extended: return false
                }
            }
            for index in removed.sorted(by: >) { entries.remove(at: index) }
        }

        // Insert in sorted order so lines sharing an anchor stay ordered among themselves
        toInsert.sort { sortKey($0.region, $0.route) < sortKey($1.region, $1.route) }

        var leftovers: [ListLine] = []
        if !placesByFit {
            leftovers = toInsert
        } else {
            for line in toInsert {
                if let index = insertionIndex(for: line, in: entries) {
                    let separator = separatorNear(index, in: entries)
                    let text = [line.region, line.route, line.waypoint1, line.waypoint2].joined(separator: separator)
                    entries.insert(Entry(raw: text + newLineSuffix, kind: classify(text), inserted: line), at: index)
                } else {
                    leftovers.append(line)
                }
            }
        }

        if !leftovers.isEmpty {
            if let last = entries.last, !last.isBoundary || last.isData { entries.append(Entry(raw: newLineSuffix, kind: .blank)) }
            let header = headerLine(title: blockTitle, styledLike: entries)
            entries.append(Entry(raw: header + newLineSuffix, kind: .header))
            for line in leftovers {
                entries.append(Entry(raw: line.text + newLineSuffix, kind: classify(line.text), inserted: line))
            }
        }

        var placements: [Placement] = []
        var currentHeader: String?
        for (i, entry) in entries.enumerated() {
            if case .header = entry.kind { currentHeader = headerText(Self.stripCR(entry.raw)) }
            if let line = entry.inserted {
                placements.append(Placement(line: line, lineNumber: i + 1, section: currentHeader))
            }
            if !entry.extendedBy.isEmpty {
                // "to" is the line as it ends up, after every widening in this batch
                let final = dataText(of: entry.raw)
                let original = entry.extendedBy[0].from
                for (n, ext) in entry.extendedBy.enumerated() {
                    placements.append(Placement(line: ext.line, lineNumber: i + 1, section: currentHeader,
                                                extended: (original, final), absorbed: n == 0 ? entry.absorbed : []))
                }
            }
        }

        var text = entries.map(\.raw).joined(separator: "\n")
        if hadTrailingNewline || existing.isEmpty { text += "\n" }
        return Result(text: text, placements: placements, duplicates: duplicates)
    }

    private static func stripCR(_ s: String) -> String {
        s.hasSuffix("\r") ? String(s.dropLast()) : s
    }

    // MARK: Extending existing lines

    private enum Extension { case notApplicable, covered, extended }

    /// Widens the line(s) on `line`'s exact route that overlap it or share an endpoint.
    /// A file line counts as the same route only if it has the same region and route name
    /// and both its waypoints are on this route's own label list — so a same-named route
    /// elsewhere, or a separate system (US20 vs US20Bus), never merges. Every touching
    /// line folds into the first; the others are removed unless they carry a comment
    /// (an overlap is harmless to TravelMapping, a lost note isn't).
    private static func extend(_ line: ListLine, in entries: inout [Entry], removed: inout Set<Int>) -> Extension {
        let labels = line.routeLabels.map { $0.uppercased() }
        // A label used twice (loops, reused junction names) makes positions ambiguous
        guard labels.count >= 2, Set(labels).count == labels.count,
              let a = labels.firstIndex(of: line.waypoint1.uppercased()),
              let b = labels.firstIndex(of: line.waypoint2.uppercased()) else { return .notApplicable }
        var lo = min(a, b), hi = max(a, b)
        let region = line.region.uppercased(), route = line.route.uppercased()

        var touching: [(index: Int, i: Int, j: Int)] = []
        for (index, entry) in entries.enumerated() where !removed.contains(index) {
            // Single-region lines, written short (R Rt A B) or long (R Rt A R Rt B)
            guard entry.isData, Set(entry.regions) == [region], Set(entry.routes) == [route],
                  entry.waypoints.count == 2,
                  let i = labels.firstIndex(of: entry.waypoints[0].uppercased()),
                  let j = labels.firstIndex(of: entry.waypoints[1].uppercased()), i != j else { continue }
            let (eLo, eHi) = (min(i, j), max(i, j))
            if eLo <= lo && hi <= eHi { return .covered }
            // Overlap or a shared endpoint; a gap (separate pieces) stays two lines
            if lo <= eHi && eLo <= hi { touching.append((index, i, j)) }
        }
        guard let first = touching.first else { return .notApplicable }
        // Other touching lines fold in only when they sit in the same block (no header or
        // blank line between) and carry no comment; anything else stays as it is — an
        // overlap is harmless to TravelMapping, a deleted line elsewhere would surprise.
        let absorbable = touching.dropFirst().filter { t in
            let range = min(first.index, t.index)...max(first.index, t.index)
            return !entries[range].contains { $0.isBoundary } && !stripCR(entries[t.index].raw).contains("#")
        }
        for t in [first] + absorbable { lo = min(lo, t.i, t.j); hi = max(hi, t.i, t.j) }

        // Rewrite the first line's waypoints in place, keeping its direction, column
        // spacing, comment and \r
        let raw = entries[first.index].raw
        let tokens = tokenRanges(in: raw)
        // Waypoints sit at token 2 and the last token in every single-region form;
        // a 5-field line only counts as "R Rt A R B" when token 3 is a region
        let fieldCount = tokens.count
        guard fieldCount == 4 || fieldCount == 6
                || (fieldCount == 5 && looksLikeRegion(String(raw[tokens[3]]), anyCase: true)) else { return .notApplicable }
        let original = tokens.map { String(raw[$0]) }
        func label(_ k: Int) -> String {
            // Endpoints that don't move keep the user's spelling
            if k == first.i { return original[2] }
            if k == first.j { return original[fieldCount - 1] }
            return line.routeLabels[k]
        }
        let (w1, w2) = first.i > first.j ? (label(hi), label(lo)) : (label(lo), label(hi))
        // Splice by pieces (String indices don't survive mutation)
        let rebuilt = String(raw[..<tokens[2].lowerBound]) + w1
            + String(raw[tokens[2].upperBound..<tokens[fieldCount - 1].lowerBound]) + w2
            + String(raw[tokens[fieldCount - 1].upperBound...])
        let before = original.joined(separator: " ")
        entries[first.index].raw = rebuilt
        entries[first.index].kind = classify(stripCR(rebuilt))
        entries[first.index].extendedBy.append((line, before))

        for t in absorbable {
            // Report the line as the user had it, even if this batch already widened it
            entries[first.index].absorbed.append(entries[t.index].extendedBy.first?.from ?? dataText(of: entries[t.index].raw))
            entries[first.index].absorbed += entries[t.index].absorbed
            // Its own widenings now describe the surviving line
            entries[first.index].extendedBy += entries[t.index].extendedBy.map { ($0.line, before) }
            removed.insert(t.index)
        }
        return .extended
    }

    /// Whitespace-separated token ranges of a line's data (before any # comment or \r)
    private static func tokenRanges(in raw: String) -> [Range<String.Index>] {
        var end = raw.firstIndex(of: "#") ?? raw.endIndex
        if end == raw.endIndex, raw.hasSuffix("\r") { end = raw.index(before: raw.endIndex) }
        var ranges: [Range<String.Index>] = []
        var i = raw.startIndex
        while i < end {
            while i < end, raw[i] == " " || raw[i] == "\t" || raw[i] == "\r" { i = raw.index(after: i) }
            guard i < end else { break }
            let start = i
            while i < end, !(raw[i] == " " || raw[i] == "\t" || raw[i] == "\r") { i = raw.index(after: i) }
            ranges.append(start..<i)
        }
        return ranges
    }

    /// A line's data, single-spaced, without comment or line ending
    private static func dataText(of raw: String) -> String {
        tokenRanges(in: raw).map { String(raw[$0]) }.joined(separator: " ")
    }

    // MARK: Fixing existing lines

    /// Whitespace-collapsed form used to match a line against TravelMapping's log
    static func normalizedLine(_ s: String) -> String {
        s.split(whereSeparator: { $0 == " " || $0 == "\t" }).joined(separator: " ")
    }

    /// Replaces existing entries — the one edit the checkup makes to lines already in the
    /// file. Lines match on their data (spacing-insensitive, ignoring a trailing # comment);
    /// the comment, line ending and the rest of the file are kept byte for byte. Keys are
    /// the line as TravelMapping's log quotes it; a value starting with "#" comments it out.
    static func applyReplacements(_ text: String, _ replacements: [String: String]) -> (text: String, applied: [String]) {
        guard !replacements.isEmpty else { return (text, []) }
        let normalize = normalizedLine
        let wanted = Dictionary(replacements.map { (normalize($0.key), $0.value) }, uniquingKeysWith: { a, _ in a })
        var applied: [String] = []
        let lines = text.components(separatedBy: "\n").map { raw -> String in
            let cr = raw.hasSuffix("\r") ? "\r" : ""
            let body = cr.isEmpty ? raw : String(raw.dropLast())
            guard !body.trimmingCharacters(in: .whitespaces).hasPrefix("#") else { return raw }
            let hashIndex = body.firstIndex(of: "#")
            let data = hashIndex.map { String(body[..<$0]) } ?? body
            guard let replacement = wanted[normalize(data)] else { return raw }
            applied.append(normalize(data))
            // Keep the spacing before an inline comment, and the comment itself
            let trailing = String(data.reversed().prefix { $0 == " " || $0 == "\t" }.reversed())
            let comment = hashIndex.map { String(body[$0...]) } ?? ""
            return replacement + (comment.isEmpty ? "" : (trailing.isEmpty ? " " : trailing) + comment) + cr
        }
        return (lines.joined(separator: "\n"), applied)
    }

    // MARK: Classification

    private static func classify(_ raw: String) -> Kind {
        let trimmed = raw.trimmingCharacters(in: .whitespaces)
        if trimmed.isEmpty { return .blank }
        if trimmed.hasPrefix("#") {
            // Indented comments are annotations on the line above; commented-out entries
            // are disabled data. Only column-0 prose comments act as section headers.
            // Long prose notes ("continued past ON427 through…") aren't headers either.
            if raw.hasPrefix("#") && trimmed.count <= 60 && parseData(String(trimmed.drop { $0 == "#" }), anyCase: false) == nil {
                return .header
            }
            return .comment
        }
        // TravelMapping matches .list entries case-insensitively, so data lines may be
        // lowercase; headers above stay strict so prose comments aren't mistaken for data.
        if let data = parseData(trimmed, anyCase: true) { return data }
        return .comment
    }

    /// Regions and routes are uppercased so matching ignores the user's casing.
    private static func parseData(_ text: String, anyCase: Bool) -> Kind? {
        let body = text.split(separator: "#", maxSplits: 1, omittingEmptySubsequences: false).first.map(String.init) ?? ""
        let f = body.split(whereSeparator: { $0 == " " || $0 == "\t" }).map(String.init)
        guard f.count >= 4, looksLikeRegion(f[0], anyCase: anyCase) else { return nil }
        let u = f.map { $0.uppercased() }
        if f.count >= 6 {
            return .data(regions: [u[0], u[3]], routes: [u[1], u[4]], waypoints: [f[2], f[5]])
        }
        if f.count == 5 && looksLikeRegion(f[3], anyCase: anyCase) {
            return .data(regions: [u[0], u[3]], routes: [u[1], u[1]], waypoints: [f[2], f[4]])
        }
        return .data(regions: [u[0]], routes: [u[1]], waypoints: [f[2], f[3]])
    }

    private static func looksLikeRegion(_ s: String, anyCase: Bool) -> Bool {
        // Region codes: "IL", "ENG", "BIH", "MEX-BC" — letters/digits/hyphens
        guard (2...7).contains(s.count), let first = s.first, first.isLetter else { return false }
        if anyCase { return s.allSatisfy { $0.isLetter || $0.isNumber || $0 == "-" } }
        guard first.isUppercase else { return false }
        return s.allSatisfy { $0.isUppercase || $0.isNumber || $0 == "-" }
    }

    private static func dedupKey(region: String, route: String, _ waypoints: [String]) -> String {
        "\(region.uppercased()) \(route.uppercased()) " + waypoints.map { $0.uppercased() }.sorted().joined(separator: " ")
    }

    // MARK: Route families & sort keys

    /// Broad route system inferred from the route name: interstates, US routes,
    /// region-prefixed state routes, or the alphabetic prefix (A, B, M, CR, …).
    static func family(region: String, route: String) -> String {
        let upper = route.uppercased()
        if upper.hasPrefix("I-") { return "interstate" }
        let prefix = String(upper.prefix { $0.isLetter })
        if prefix == "US" { return "us" }
        let regionLetters = String(region.uppercased().split(separator: "-").last ?? "")
        if !prefix.isEmpty && prefix == regionLetters { return "state" }
        return "prefix:\(prefix)"
    }

    private static func routeNumber(_ route: String) -> (Int, String) {
        let digits = route.drop { !$0.isNumber }
        let number = Int(String(digits.prefix { $0.isNumber })) ?? Int.max
        return (number, String(digits.drop { $0.isNumber }))
    }

    private struct SortKey: Comparable {
        let number: Int
        let suffix: String
        let region: String
        let route: String
        static func < (a: SortKey, b: SortKey) -> Bool {
            (a.number, a.suffix, a.region) < (b.number, b.suffix, b.region)
        }
    }

    private static func sortKey(_ region: String, _ route: String) -> SortKey {
        let (n, s) = routeNumber(route)
        return SortKey(number: n, suffix: s, region: region, route: route)
    }

    /// Orderings people actually use within a block
    private enum Ordering: CaseIterable {
        case byRegionThenRouteNumeric   // natural sort: FL I-4, FL I-10 …
        case byRegionThenRouteLexical   // plain sort: AL AL295, AR AR102, FL I-10, FL I-4 …
        case byRouteNumber              // US Interstates: I-4, I-5, I-10 … (any region order)

        func inOrder(_ a: (String, String), _ b: (String, String)) -> Bool {
            switch self {
            case .byRouteNumber:
                let ka = routeNumber(a.1), kb = routeNumber(b.1)
                return ka.0 != kb.0 ? ka.0 < kb.0 : ka.1 <= kb.1
            case .byRegionThenRouteLexical:
                return a.0 != b.0 ? a.0 < b.0 : a.1 <= b.1
            case .byRegionThenRouteNumeric:
                if a.0 != b.0 { return a.0 < b.0 }
                return a.1.compare(b.1, options: [.numeric]) != .orderedDescending
            }
        }
    }

    // MARK: Placement

    private static func insertionIndex(for original: ListLine, in entries: [Entry]) -> Int? {
        let line = ListLine(region: original.region.uppercased(), route: original.route.uppercased(),
                            waypoint1: original.waypoint1, waypoint2: original.waypoint2)
        let fam = family(region: line.region, route: line.route)
        let crossRegion = fam == "interstate" || fam == "us"

        // Tiers from most to least specific; first non-empty one wins
        let tiers: [(Entry) -> Bool] = [
            { $0.regions.contains(line.region) && $0.routes.contains(line.route) },
            { crossRegion && $0.routes.contains(line.route) },
            { $0.primaryRegion == line.region && family(region: $0.primaryRegion, route: $0.primaryRoute) == fam },
            // Only nationwide systems group across regions; a new state's routes get their own block
            { crossRegion && family(region: $0.primaryRegion, route: $0.primaryRoute) == fam },
            { $0.regions.contains(line.region) },
        ]

        for (tier, matches) in tiers.enumerated() {
            let anchors = entries.indices.filter { entries[$0].isData && matches(entries[$0]) }
            guard let lastAnchor = anchors.last else { continue }

            // When a tier's matches span several blocks, prefer the block with the most
            // matches (e.g. the "#US Interstates" section over a stray interstate under
            // a state heading).
            let anchor = bestBlockAnchor(anchors, in: entries) ?? lastAnchor
            let block = blockRange(around: anchor, in: entries)
            let blockData = block.filter { entries[$0].isData }

            if let ordering = detectOrdering(blockData.map { (entries[$0].primaryRegion, entries[$0].primaryRoute) }) {
                return sortedPosition(for: (line.region, line.route), among: blockData, in: entries, ordering: ordering)
            }

            // Unsorted block: sit beside the same route when we have it, else end of block
            if tier <= 1 {
                return (anchors.filter { block.contains($0) }.last ?? anchor) + 1
            }
            return (blockData.last ?? anchor) + 1
        }
        return nil
    }

    /// Insertion index that leaves the fewest out-of-order neighbors — tolerant of the
    /// occasional hand-placed line in an otherwise sorted block.
    private static func sortedPosition(for key: (String, String), among blockData: [Int], in entries: [Entry], ordering: Ordering) -> Int {
        let keys = blockData.map { (entries[$0].primaryRegion, entries[$0].primaryRoute) }
        // violations(p) = lines before p that sort after key + lines from p on that sort before key
        var before = 0
        var after = keys.filter { !ordering.inOrder(key, $0) }.count
        var best = (violations: after, position: 0)
        for (i, k) in keys.enumerated() {
            if !ordering.inOrder(k, key) { before += 1 }
            if !ordering.inOrder(key, k) { after -= 1 }
            // `<=` places ties after existing equal keys, beside the same route
            if before + after <= best.violations { best = (before + after, i + 1) }
        }
        return best.position == 0 ? blockData[0] : blockData[best.position - 1] + 1
    }

    private static func bestBlockAnchor(_ anchors: [Int], in entries: [Entry]) -> Int? {
        // One pass for every line's block start — calling blockRange per anchor is
        // quadratic on big unsectioned files (15k lines, thousands of anchors).
        var blockStart = [Int](repeating: 0, count: entries.count)
        var current = 0
        for i in entries.indices {
            if i > 0 && entries[i - 1].isBoundary { current = i }
            blockStart[i] = current
        }
        var counts: [Int: (count: Int, last: Int)] = [:]
        for a in anchors {
            let start = blockStart[a]
            let c = counts[start]
            counts[start] = ((c?.count ?? 0) + 1, a)
        }
        return counts.values.max { $0.count < $1.count }?.last
    }

    /// Lines between the nearest boundaries (section header or blank line) around `index`.
    private static func blockRange(around index: Int, in entries: [Entry]) -> Range<Int> {
        var lo = index
        while lo > 0 && !entries[lo - 1].isBoundary { lo -= 1 }
        var hi = index + 1
        while hi < entries.count && !entries[hi].isBoundary { hi += 1 }
        return lo..<hi
    }

    private static func detectOrdering(_ items: [(String, String)]) -> Ordering? {
        guard items.count >= 3 else { return nil }
        let pairs = Array(zip(items, items.dropFirst()))
        // Best-fitting ordering wins; allCases order breaks ties (natural sort before plain)
        let scored = Ordering.allCases.map { ordering in
            (ordering, Double(pairs.filter { ordering.inOrder($0.0, $0.1) }.count) / Double(pairs.count))
        }
        guard let best = scored.max(by: { $0.1 < $1.1 }), best.1 >= 0.9 else { return nil }
        return best.0
    }

    private static func separatorNear(_ index: Int, in entries: [Entry]) -> String {
        let neighbor = entries[max(0, min(index - 1, entries.count - 1))...].first { $0.isData }
        return neighbor?.raw.contains("\t") == true ? "\t" : " "
    }

    // MARK: Chronological files & headers

    private static let datePattern = try! NSRegularExpression(
        pattern: #"(\d{4}-\d{1,2}-\d{1,2})|(\d{1,2}/\d{1,2}/\d{2,4})|((Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\.? \d{1,2}?,? ?\d{4})"#
    )

    /// Files whose sections are dated trip blocks get new lines appended as a new block.
    private static func isChronological(_ entries: [Entry]) -> Bool {
        let headers = entries.filter { if case .header = $0.kind { return true } else { return false } }
        let dated = headers.filter {
            datePattern.firstMatch(in: $0.raw, range: NSRange($0.raw.startIndex..., in: $0.raw)) != nil
        }
        // Dated headers must make up most of the file's later sections
        guard dated.count >= 3 else { return false }
        return Double(dated.count) / Double(headers.count) >= 0.5
            || entries.lastIndex(where: { if case .header = $0.kind { return true } else { return false } })
                .map { datePattern.firstMatch(in: entries[$0].raw, range: NSRange(entries[$0].raw.startIndex..., in: entries[$0].raw)) != nil } == true
    }

    private static func headerText(_ raw: String) -> String {
        raw.trimmingCharacters(in: CharacterSet(charactersIn: "#-= \t"))
    }

    private static func headerLine(title: String, styledLike entries: [Entry]) -> String {
        let headers = entries.filter { if case .header = $0.kind { return true } else { return false } }.map { stripCR($0.raw) }
        if headers.contains(where: { $0.hasPrefix("##") && $0.hasSuffix("##") }) { return "##\(title)##" }
        if headers.contains(where: { $0.hasPrefix("# ") }) || headers.isEmpty { return "# \(title)" }
        return "#\(title)"
    }
}
